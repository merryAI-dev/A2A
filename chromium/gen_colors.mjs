#!/usr/bin/env node
// 브라우저 틀(C++)의 색을 앱 화면 CSS의 밝은 톤에서 뽑는다 — 색의 원본은 tokens.css 하나.
//   node chromium/gen_colors.mjs <tokens.css> <출력.h>
import fs from 'node:fs';

const [css, out] = process.argv.slice(2);
const block = fs.readFileSync(css, 'utf8').match(/\[data-tone="light"\]\s*\{([\s\S]*?)\}/)?.[1];
if (!block) throw new Error('밝은 톤 블록을 찾지 못했습니다');

const NAMES = { raise: 'Raise', card: 'Card', field: 'Field', 'card-ink': 'CardInk', 'card-sub': 'CardSub', 'card-line': 'CardLine' };
const lines = Object.entries(NAMES).map(([token, name]) => {
  const raw = block.match(new RegExp(`--${token}:\\s*#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})\\s*;`))?.[1];
  if (!raw) throw new Error(`--${token} 값을 찾지 못했습니다`);
  const hex = raw.length === 3 ? [...raw].map((c) => c + c).join('') : raw;
  const [r, g, b] = [0, 2, 4].map((i) => `0x${hex.slice(i, i + 2)}`);
  return `inline constexpr SkColor kA2A${name} = SkColorSetRGB(${r}, ${g}, ${b});`;
});

fs.writeFileSync(out, `// Generated by A2A/chromium/gen_colors.mjs from tokens.css. Do not edit.
#ifndef A2A_A2A_COLORS_H_
#define A2A_A2A_COLORS_H_

#include "third_party/skia/include/core/SkColor.h"

${lines.join('\n')}

#endif  // A2A_A2A_COLORS_H_
`);
